/// Металл медали: цвета переливов и цвет самой гравировки.
class MedalMetal {
  const MedalMetal(this.light, this.base, this.shine, this.dark, this.ink);

  final Color light;
  final Color base;
  final Color shine;
  final Color dark;

  /// Цвет гравировки — тёмный оттенок самого металла, а не чёрный:
  /// выбитый след остаётся металлом, просто в тени.
  final Color ink;

  static const gold = MedalMetal(
    Color(0xFFF3D488), Color(0xFFC08A2E), Color(0xFFFBE6A8),
    Color(0xFFA96C1C), Color(0xC72E1F06),
  );
  static const silver = MedalMetal(
    Color(0xFFE9EEF2), Color(0xFF8D949B), Color(0xFFF5F8FA),
    Color(0xFF6E767E), Color(0xB8181E22),
  );
  static const bronze = MedalMetal(
    Color(0xFFD68B4F), Color(0xFF8A5124), Color(0xFFE5A163),
    Color(0xFF6E3D18), Color(0xC72C1606),
  );

  static MedalMetal of(String tier) => switch (tier) {
        'gold' => gold,
        'bronze' => bronze,
        _ => silver,
      };

  static String nameOf(String tier) => switch (tier) {
        'gold' => 'Золото',
        'bronze' => 'Бронза',
        _ => 'Серебро',
      };
}
