/// Локализация названия города. Возвращает оригинал, если города нет в словаре.
/// Города Казахстана — основной охват, добавляй по мере необходимости.
String localizeCity(BuildContext context, String? city) {
  if (city == null || city.isEmpty) return '';
  final locale = Localizations.localeOf(context).languageCode;
  if (locale == 'ru') return city; // данные в БД уже на русском
  final map = locale == 'kk' ? _kk : _en;
  return map[city.trim()] ?? city;
}

